function typoEditBudget(len) {
  const n = Math.max(0, len | 0);
  /* A 4-5 letter word may be off by one slip, never two ("blah" is not "bash"). */
  if (n <= 2) return 0;
  if (n <= 5) return 1;
  if (n <= 11) return 2;
  return 3;
}

/** True when longer is shorter plus one inserted character (any position). */
function oneCharInsertionDeletion(shorter, longer) {
  if (shorter.length + 1 !== longer.length) return false;
  if (shorter.length > longer.length) {
    const t = shorter;
    shorter = longer;
    longer = t;
  }
  let i = 0;
  let j = 0;
  while (i < shorter.length && j < longer.length) {
    if (shorter[i] === longer[j]) {
      i += 1;
      j += 1;
      continue;
    }
    j += 1;
  }
  return i === shorter.length;
}

/**
 * Edit distance allowed for this pair, or null if too far / ambiguous anchor.
 * Supports missing letters anywhere, dropped first letter, and one substitution.
 */
/** Edit distance where swapping two neighbouring letters counts as one slip ("maekup" → "makeup" is 1, not 2). */
function osaDistance(a, b) {
  const la = a.length;
  const lb = b.length;
  if (!la) return lb;
  if (!lb) return la;
  const d = [];
  for (let i = 0; i <= la; i++) {
    d[i] = [i];
  }
  for (let j = 1; j <= lb; j++) d[0][j] = j;
  for (let i = 1; i <= la; i++) {
    for (let j = 1; j <= lb; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      let v = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + cost);
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) v = Math.min(v, d[i - 2][j - 2] + 1);
      d[i][j] = v;
    }
  }
  return d[la][lb];
}

function typoMatchScore(q, c) {
  if (q === c) return 0;
  const budget = typoEditBudget(Math.max(q.length, c.length));
  if (Math.abs(q.length - c.length) > budget) return null;
  const d = osaDistance(q, c);
  if (d > budget) return null;
  if (d === 0) return 0;
  if (q[0] === c[0]) return d;
  if (oneCharInsertionDeletion(q, c)) return d;
  if (q.length + 1 === c.length && q === c.slice(1)) return d;
  if (c.length + 1 === q.length && c === q.slice(1)) return d;
  if (d === 1 && q.length === c.length) return d;
  return null;
}

