var LIB_FIELD_TRAIL = [];

function libFieldByName(category) {
  const c = String(category || "");
  if (!c) return null;
  for (let i = 0; i < LIB_FIELD_RULES.length; i++) {
    if (LIB_FIELD_RULES[i][1].test(c)) return LIB_FIELD_RULES[i][0];
  }
  return null;
}

/** Field of every lesson (named categories by rule; "Wikipedia" and unnamed ones by their words) plus how near the fields are. */
function libFieldModel(idx) {
  if (idx.fieldModel) return idx.fieldModel;
  const fieldOf = new Map();
  const counts = new Map();
  const loose = [];
  const addWords = (field, d) => {
    let m = counts.get(field);
    if (!m) {
      m = new Map();
      counts.set(field, m);
    }
    d.q.forEach(w => m.set(w, (m.get(w) || 0) + 1));
    d.t.forEach(w => m.set(w, (m.get(w) || 0) + 1));
  };
  idx.docs.forEach(d => {
    const name = libFieldByName(d.fact && d.fact.category);
    if (name) {
      fieldOf.set(d, name);
      if (name !== LIB_FIELD_EXCLUDED) addWords(name, d);
    } else loose.push(d);
  });
  const fields = Array.from(counts.keys());
  const F = fields.length || 1;
  const dfField = new Map();
  counts.forEach(m => m.forEach((_, w) => dfField.set(w, (dfField.get(w) || 0) + 1)));
  const vec = new Map();
  fields.forEach(f => {
    const w = new Map();
    let norm = 0;
    counts.get(f).forEach((c, word) => {
      const x = Math.log(1 + c) * Math.log(F / dfField.get(word));
      if (x > 0) {
        w.set(word, x);
        norm += x * x;
      }
    });
    vec.set(f, { w, norm: Math.sqrt(norm) || 1 });
  });
  const classify = words => {
    let best = null;
    let bestScore = 0;
    fields.forEach(f => {
      const v = vec.get(f);
      let sum = 0;
      words.forEach(w => {
        const x = v.w.get(w);
        if (x) sum += x;
      });
      sum /= v.norm;
      if (sum > bestScore) {
        best = f;
        bestScore = sum;
      }
    });
    return best;
  };
  loose.forEach(d => {
    const words = new Set();
    d.q.forEach(w => words.add(w));
    d.t.forEach(w => words.add(w));
    fieldOf.set(d, classify(words));
  });
  const cosine = (a, b) => {
    let dot = 0;
    const small = a.w.size < b.w.size ? a : b;
    const large = small === a ? b : a;
    small.w.forEach((x, w) => {
      const y = large.w.get(w);
      if (y) dot += x * y;
    });
    return dot / (a.norm * b.norm);
  };
  const neighbors = new Map();
  fields.forEach(f => {
    neighbors.set(
      f,
      fields
        .filter(g => g !== f)
        .map(g => ({ field: g, sim: cosine(vec.get(f), vec.get(g)) }))
        .sort((x, y) => y.sim - x.sim)
    );
  });
  idx.fieldModel = { fields, neighbors, fieldOf, classify };
  return idx.fieldModel;
}

/**
 * Menu of everything the library knows, grouped by field: [{ field, total, categories: [{ name, count }] }].
 * Covers every category of every facts file and the taught lessons. Restricted topics sit in their own last group.
 */
function libCategoryMenu(userLessons) {
  const idx = libSuggestIndex(userLessons);
  const model = libFieldModel(idx);
  const cats = new Map();
  idx.docs.forEach(d => {
    const name = (d.fact && d.fact.category) || "Other";
    let e = cats.get(name);
    if (!e) {
      e = { name, count: 0, votes: new Map() };
      cats.set(name, e);
    }
    e.count++;
    const f = model.fieldOf.get(d);
    if (f) e.votes.set(f, (e.votes.get(f) || 0) + 1);
  });
  const groups = new Map();
  cats.forEach(e => {
    let field = libFieldByName(e.name);
    if (!field) {
      if (e.name === "Wikipedia" || e.name === "Learned") field = "Wikipedia & learned";
      else {
        const top = Array.from(e.votes.entries()).sort((x, y) => y[1] - x[1])[0];
        field = top ? top[0] : "Other";
      }
    }
    if (!groups.has(field)) groups.set(field, { field, total: 0, categories: [] });
    const g = groups.get(field);
    g.total += e.count;
    g.categories.push({ name: e.name, count: e.count });
  });
  const list = Array.from(groups.values());
  list.forEach(g => g.categories.sort((x, y) => y.count - x.count));
  list.forEach(g => (g.selectable = model.fields.indexOf(g.field) !== -1));
  const restricted = list.filter(g => g.field === LIB_FIELD_EXCLUDED);
  restricted.forEach(g => (g.field = "Restricted topics"));
  const catchAll = list.filter(g => g.field === "Wikipedia & learned");
  return list
    .filter(g => restricted.indexOf(g) === -1 && catchAll.indexOf(g) === -1)
    .sort((x, y) => y.total - x.total)
    .concat(catchAll, restricted);
}

/** A random stored question from a category ({ category }), a field ({ field }) or anywhere ({}); prefers broad questions with real answers. */
function libRandomQuestionIn(selector, userLessons, avoid) {
  const idx = libSuggestIndex(userLessons);
  const model = libFieldModel(idx);
  const sel = selector || {};
  const skip = avoid instanceof Set ? avoid : new Set(avoid || []);
  const inScope = d => {
    if (!d.qs || skip.has(d.qk)) return false;
    if (sel.category) return (d.fact && d.fact.category) === sel.category;
    if (sel.field) {
      const f = model.fieldOf.get(d);
      return f === sel.field && f !== LIB_FIELD_EXCLUDED;
    }
    return model.fieldOf.get(d) !== LIB_FIELD_EXCLUDED;
  };
  const scoped = idx.docs.filter(inScope);
  const strict = scoped.filter(
    d => d.qs.length <= 90 && /^(what|how|why|who|which|when|where)\b/i.test(d.qs) && String((d.fact && d.fact.text) || "").length >= 60
  );
  const pool = strict.length ? strict : scoped;
  if (!pool.length) return null;
  const d = pool[Math.floor(Math.random() * pool.length)];
  return { q: libSuggestAsQuestion(d.qs), category: (d.fact && d.fact.category) || "", field: model.fieldOf.get(d) || "" };
}

/** Up to `count` of the most useful questions of one category or a list of categories (shuffled among the best-scoring ones): [{ q, text, key }]. */
function libRandomFactsIn(category, userLessons, count, avoid) {
  const idx = libSuggestIndex(userLessons);
  const skip = avoid instanceof Set ? avoid : new Set(avoid || []);
  const inCategory = new Set(Array.isArray(category) ? category : [category]);
  const seen = new Set();
  const scored = [];
  idx.docs.forEach(d => {
    if (!d.qs || !d.fact || !inCategory.has(d.fact.category) || seen.has(d.qk)) return;
    const text = String(d.fact.text || "");
    if (text.length < 40 || d.qs.length > 100 || d.qs.length < 14) return;
    seen.add(d.qk);
    let score = 0;
    if (d.fact.question) score += 3;
    else {
      /* Auto-made "What is X?" questions are a fallback; odd-looking subjects (ending in a verb form) rank last. */
      score -= 3;
      const subject = d.qs.replace(/^what (is|are) /i, "").replace(/\?+$/, "");
      if (subject.split(/\s+/).length > 4 || /(?:[^s]s|es)$/i.test(subject)) score -= 3;
    }
    if (/^(how|why|what should|what to|when|which|who|where|can|is it|should)\b/i.test(d.qs)) score += 2;
    else if (/^what\b/i.test(d.qs)) score += 1;
    if (/\b(how to|what to do|why|safe|safely|should|difference|cause|prevent|avoid|work|best|common|mean)\b/i.test(d.qs)) score += 1;
    if (text.length >= 90 && text.length <= 500) score += 1;
    if (skip.has(d.qk)) score -= 6;
    scored.push({ d, score: score + Math.random() * 2.5 });
  });
  scored.sort((a, b) => b.score - a.score);

  const catList = Array.isArray(category) ? category : [category];
  let chosen = scored;
  if (catList.length > 1) {
    /* Explore merges several library categories (e.g. Geography + Places). Top-score-only
       would show five similar "which/where" rows from one subcategory (often Bulgarian Geography). */
    const byCat = new Map(catList.map((c) => [c, []]));
    scored.forEach((row) => {
      const c = row.d.fact && row.d.fact.category;
      if (byCat.has(c)) byCat.get(c).push(row);
    });
    const merged = [];
    let round = 0;
    while (merged.length < count) {
      let added = false;
      for (const c of catList) {
        const bucket = byCat.get(c) || [];
        if (round < bucket.length && merged.length < count) {
          merged.push(bucket[round]);
          added = true;
        }
      }
      if (!added) break;
      round += 1;
    }
    if (merged.length) chosen = merged;
  } else {
    chosen = scored.slice(0, count);
  }

  return chosen.slice(0, count).map(({ d }) => ({
    q: libSuggestAsQuestion(d.qs),
    text: String(d.fact.text),
    key: d.qk
  }));
}

function relatedQuestions(prompt, facts, userLessons, max, shortFacts, seenQuestions) {
  const idx = libSuggestIndex(userLessons);
  const N = idx.docs.length || 1;
  const askedKey = libSuggestNorm(prompt);
  const shown = new Set();
  const currentCategories = new Set();
  const qw = new Set(questionContent(prompt));
  const tw = new Set();
  (facts || []).forEach(f => {
    if (!f) return;
    if (f.text) shown.add(libSuggestNorm(f.text));
    if (f.category) currentCategories.add(f.category);
    questionContent(f.question || "").forEach(w => qw.add(w));
    questionContent(String(f.text || "").slice(0, 400)).forEach(w => tw.add(w));
  });
  /* A category named in the question ("survival", "how to survive…") outranks whatever category the matched facts happen to be in. */
  const promptCategories = new Set();
  const promptWords = (String(prompt || "").toLowerCase().match(/[a-z]{5,}/g) || []).map(w => w.replace(/s$/, ""));
  idx.docs.forEach(d => {
    const c = d.fact && d.fact.category;
    if (!c || promptCategories.has(c) || !/^[A-Za-z]{5,}$/.test(c)) return;
    const stem = c.toLowerCase().replace(/s$/, "");
    const prefix = Math.min(6, stem.length);
    if (promptWords.some(w => w === stem || w.slice(0, prefix) === stem.slice(0, prefix))) promptCategories.add(c);
  });
  if (promptCategories.size) {
    currentCategories.clear();
    promptCategories.forEach(c => currentCategories.add(c));
  }
  const seen = seenQuestions instanceof Set ? seenQuestions : new Set(seenQuestions || []);
  const rareMax = N * 0.03;
  const weight = w => Math.log(N / (1 + (idx.df.get(w) || 0)));
  const scoreQuestion = (qk, qWords, tWords) => {
    if (!qk || qk === askedKey || seen.has(qk)) return 0;
    let score = 0;
    let rare = 0;
    let rarest = Infinity;
    let fromPrompt = 0;
    const take = (w, mult) => {
      const df = idx.df.get(w) || 0;
      if (df > rareMax) return;
      score += mult * weight(w);
      rare++;
      rarest = Math.min(rarest, df);
    };
    qw.forEach(w => {
      if (qWords.has(w) || tWords.has(w)) {
        take(w, 2);
        fromPrompt++;
      }
    });
    const rareBeforeTw = rare;
    tw.forEach(w => {
      if (!qw.has(w) && qWords.has(w)) take(w, 1);
    });
    const fromAnswer = rare - rareBeforeTw;
    /* Answer-text spillover alone (e.g. "river" → any question containing "rivers") is too loose for Related. */
    if (!fromPrompt && fromAnswer < 2) return 0;
    if (!fromPrompt && fromAnswer === 1 && rarest > 25) return 0;
    return rare >= 2 || (rare === 1 && rarest <= 8) ? score : 0;
  };
  const model = libFieldModel(idx);
  const longCandidates = [];
  const allLongCandidates = [];
  idx.docs.forEach(d => {
    const f = d.fact;
    if (!f || shown.has(d.tk)) return;
    const q = d.qs;
    if (!q || seen.has(d.qk)) return;
    const score = scoreQuestion(d.qk, d.qc, d.t);
    const cand = { q, category: f.category || "Other", score, doc: d, field: model.fieldOf.get(d) || null };
    allLongCandidates.push(cand);
    if (score) longCandidates.push(cand);
  });

  const shortCandidates = [];
  const allShortCandidates = [];
  (shortFacts || []).forEach(f => {
    if (!f || !f.question || shown.has(libSuggestNorm(f.text))) return;
    if (seen.has(libSuggestNorm(f.question))) return;
    const score = scoreQuestion(
      libSuggestNorm(f.question),
      new Set(questionContent(f.question)),
      new Set(questionContent(String(f.text || "").slice(0, 400)))
    );
    const shortWords = new Set(questionContent(f.question + " " + String(f.text || "").slice(0, 200)));
    const shortCand = { q: f.question, category: "Small network", score, field: model.classify(shortWords) };
    allShortCandidates.push(shortCand);
    if (score) shortCandidates.push(shortCand);
  });

  const limit = Math.max(1, max || 3);
  const typedSets = libSuggestTypedSets(prompt, seen);
  const out = [];
  const used = new Set([askedKey]);
  const add = candidate => {
    if (!candidate) return false;
    const q = libSuggestAsQuestion(candidate.q);
    const key = libSuggestNorm(q);
    if (!key || used.has(key) || seen.has(key)) return false;
    const qSet = new Set(questionContent(q));
    if (typedSets.some(t => libSuggestNearDuplicate(qSet, t))) return false;
    used.add(key);
    out.push(q);
    return true;
  };
  const pickRandom = list => (list.length ? list[Math.floor(Math.random() * list.length)] : null);
  const byScore = list => list.slice().sort((x, y) => y.score - x.score);

  /* 1) Two chips that follow the prompt: the best match, then one of the next best (kept varied). */
  const allRelevant = byScore(longCandidates.concat(shortCandidates));
  const inPromptField = allRelevant.filter(c => promptCategories.has(c.category));
  const relevant = inPromptField.length ? inPromptField : allRelevant;
  const relatedCats = new Set();
  const first = relevant[0];
  if (first && add(first)) relatedCats.add(first.category);
  const nearby = relevant.slice(1, 7).filter(c => !used.has(libSuggestNorm(libSuggestAsQuestion(c.q))));
  const secondPool = nearby.length
    ? nearby.filter(c => first && c.field && first.field && c.field === first.field).concat(nearby)
    : [];
  const second = secondPool[0] || null;
  if (second && add(second)) relatedCats.add(second.category);

  /* Not enough on-topic lessons: stay in the same field as the answer before anything else. */
  const sameFieldCats = new Set(currentCategories);
  relatedCats.forEach(c => sameFieldCats.add(c));
  const sameField = allLongCandidates.concat(allShortCandidates).filter(c => sameFieldCats.has(c.category));
  while (out.length < Math.min(2, limit) && sameField.length) {
    const pick = sameField.splice(Math.floor(Math.random() * sameField.length), 1)[0];
    if (add(pick)) relatedCats.add(pick.category);
  }

  /* 2) Third chip only: hop to another field (random question + dropdown to swap field). */
  const meta = {};
  if (limit < 3) {
    out.meta = meta;
    return out;
  }
  const everything = allLongCandidates.concat(allShortCandidates);
  const fieldCounts = new Map();
  const bump = f => {
    if (f && f !== LIB_FIELD_EXCLUDED) fieldCounts.set(f, (fieldCounts.get(f) || 0) + 1);
  };
  (facts || []).forEach(f => bump(f && libFieldByName(f.category)));
  [first, second].forEach(c => c && bump(c.field));
  if (!fieldCounts.size) bump(model.classify(new Set(Array.from(qw).concat(Array.from(tw)))));
  const currentFields = new Set(fieldCounts.keys());
  const primaryField = Array.from(fieldCounts.entries()).sort((x, y) => y[1] - x[1]).map(x => x[0])[0] || null;

  let hopField = null;
  const near = primaryField ? (model.neighbors.get(primaryField) || []).filter(n => !currentFields.has(n.field)) : [];
  const fresh = near.filter(n => LIB_FIELD_TRAIL.indexOf(n.field) === -1);
  const closest = (fresh.length ? fresh : near).slice(0, 3);
  if (!closest.length || Math.random() < 0.2) {
    /* Wild card: any other field, preferring ones not visited yet. */
    const others = model.fields.filter(f => !currentFields.has(f));
    hopField = pickRandom(others.filter(f => LIB_FIELD_TRAIL.indexOf(f) === -1)) || pickRandom(others);
  } else {
    let roll = Math.random() * closest.reduce((sum, n) => sum + n.sim, 0);
    hopField = closest[closest.length - 1].field;
    for (const n of closest) {
      roll -= n.sim;
      if (roll <= 0) {
        hopField = n.field;
        break;
      }
    }
  }

  let hopped = false;
  if (hopField) {
    const bridgeWords = new Set(Array.from(qw).concat(Array.from(tw)));
    /* Only specific words make a bridge: "hypothermia" or "compass", not "example" or "work". */
    const bridgeMax = N * 0.01;
    const good = everything.filter(c => {
      if (c.field !== hopField || !c.q || c.q.length > 90) return false;
      if (!/^(what|how|why|who|which|when|where)\b/i.test(c.q)) return false;
      const text = c.doc && c.doc.fact && c.doc.fact.text;
      return !c.doc || String(text || "").length >= 60;
    });
    const bridged = good
      .map(c => {
        let sc = 0;
        let shared = 0;
        let word = "";
        if (c.doc) {
          c.doc.qc.forEach(w => {
            const dfw = idx.df.get(w) || 0;
            if (!bridgeWords.has(w) || dfw < 2 || dfw > bridgeMax) return;
            const wt = weight(w);
            sc += wt;
            shared++;
            if (!word || wt > weight(word)) word = w;
          });
        }
        return { c, sc, shared, word };
      })
      .filter(r => r.shared >= 2 || (r.shared === 1 && (idx.df.get(r.word) || 0) <= 25))
      .sort((x, y) => y.sc - x.sc);
    const markHop = c => {
      meta[libSuggestAsQuestion(c.q)] = { field: hopField, bridge: "" };
    };
    const tryHop = c => {
      if (out.length >= limit) return false;
      if (add(c)) {
        markHop(c);
        hopped = true;
        return true;
      }
      return false;
    };
    const pick = bridged.length ? pickRandom(bridged.slice(0, 3)) : null;
    let tries;
    if (pick) {
      tries = [pick].concat(bridged.filter(r => r !== pick)).slice(0, 6);
      for (const r of tries) {
        if (add(r.c)) {
          meta[libSuggestAsQuestion(r.c.q)] = { field: hopField, bridge: r.word || "" };
          hopped = true;
          break;
        }
      }
    } else {
      /* Third chip: random starter question in another field (dropdown lets them pick a different field). */
      const broad = good.filter(c => /^what (is|are)\b/i.test(c.q));
      const poolRep = broad.length >= 3 ? broad : good;
      tries = poolRep
        .slice()
        .sort(() => Math.random() - 0.5)
        .slice(0, 8)
        .map(c => ({ c }));
      for (const r of tries) {
        if (tryHop(r.c)) break;
      }
    }
  }
  if (hopped) {
    if (primaryField && LIB_FIELD_TRAIL[LIB_FIELD_TRAIL.length - 1] !== primaryField) LIB_FIELD_TRAIL.push(primaryField);
    LIB_FIELD_TRAIL.push(hopField);
    while (LIB_FIELD_TRAIL.length > 6) LIB_FIELD_TRAIL.shift();
  }

  /* Slot 3 is always the field hop above — never pad with another unrelated Related chip. */
  if (limit >= 3 && out.length === 3 && !hopped) {
    out.pop();
  }
  out.meta = meta;
  return out;
}

function lessonDisplaySource(fact) {
  if (!fact || fact.id == null) return "from Lesson";
  if (fact.category === "Wikipedia") return "Deep network learned #" + fact.id;
  return "from " + (fact.category || "Lesson") + " #" + fact.id;
}

function lessonReasonSource(picked, conflict) {
  if (!picked || !picked.length) return "";
  if (picked.length === 1 && picked[0].fact && picked[0].fact.category === "Wikipedia") {
    return lessonDisplaySource(picked[0].fact);
  }
  const ids = picked.map(h => {
    const f = h.fact;
    if (f && f.category === "Wikipedia") return "Deep network learned #" + f.id;
    return (f.category || "Lesson") + " #" + f.id;
  }).join(" and ");
  return (conflict ? "two lessons, " : "from ") + ids;
}

function searchScienceLibrary(prompt) {
  return answerFromLessons(prompt, []);
}

/** Stored lesson question for a deep pass when the user prompt is loose (e.g. titanium?). */
function lessonDeepQuestion(facts, prompt) {
  if (!facts || !facts.length) return prompt;
  const fact = facts[0];
  const stored = String(fact.question || "")
    .trim()
    .replace(/\?+$/, "");
  if (!stored) return prompt;
  if (questionMatches(prompt, fact)) return stored + " ?";
  if (questionPromptOverlap(prompt, fact)) return stored + " ?";
  if (asksDefinition(prompt)) {
    const subject = questionContent(prompt)[0];
    if (subject && definesSubject(fact.text, subject)) return stored + " ?";
  }
  const asked = scienceTokens(prompt);
  if (asked.length === 1 && scienceStem(asked[0])) {
    const stem = scienceStem(asked[0]);
    if (scienceTokens(fact.text).some(w => queryStemMatchesVocab(stem, scienceStem(w)))) return stored + " ?";
  }
  return prompt;
}
