/** Question openers (shape / ask-word detection). */
const SCIENCE_ASK = ["what", "when", "where", "who", "why", "how", "which"];

let _scienceFunctionLexicon = null;

/** Stop + ask words (length ≥ 3) — typo repair on any token in the question. */
function scienceFunctionLexicon() {
  if (!_scienceFunctionLexicon) {
    _scienceFunctionLexicon = new Set();
    SCIENCE_ASK.forEach(w => _scienceFunctionLexicon.add(w));
    SCIENCE_STOP.forEach(w => {
      if (w.length >= 3) _scienceFunctionLexicon.add(w);
    });
  }
  return _scienceFunctionLexicon;
}

function typoEditBudget(len) {
  const n = Math.max(0, len | 0);
  if (n <= 2) return 0;
  if (n === 3) return 1;
  if (n <= 7) return 2;
  if (n <= 11) return 2;
  return 3;
}

/** True when longer is shorter plus one inserted character (any position). */
function oneCharInsertionDeletion(shorter, longer) {
  if (shorter.length + 1 !== longer.length) return false;
  if (shorter.length > longer.length) {
    const t = shorter;
    shorter = longer;
    longer = t;
  }
  let i = 0;
  let j = 0;
  while (i < shorter.length && j < longer.length) {
    if (shorter[i] === longer[j]) {
      i += 1;
      j += 1;
      continue;
    }
    j += 1;
  }
  return i === shorter.length;
}

/**
 * Edit distance allowed for this pair, or null if too far / ambiguous anchor.
 * Supports missing letters anywhere, dropped first letter, and one substitution.
 */
function typoMatchScore(q, c) {
  if (q === c) return 0;
  const d = levenshtein(q, c);
  const budget = typoEditBudget(Math.max(q.length, c.length));
  if (d > budget) return null;
  if (d === 0) return 0;
  if (q[0] === c[0]) return d;
  if (oneCharInsertionDeletion(q, c)) return d;
  if (q.length + 1 === c.length && q === c.slice(1)) return d;
  if (c.length + 1 === q.length && c === q.slice(1)) return d;
  if (d === 1 && q.length === c.length) return d;
  return null;
}

/**
 * Best unique lexicon match for a token (function words or lesson vocabulary stems).
 */
function fuzzyBestInLexicon(query, lexiconIterable, minCandLen) {
  const minLen = 3;
  const q = scienceStem(query);
  if (lexiconIterable.has && (lexiconIterable.has(query) || lexiconIterable.has(q))) {
    return lexiconIterable.has(q) ? q : query;
  }
  if (q.length < minLen) return null;
  const seenStem = new Set();
  let best = null;
  let bestD = 999;
  let tie = false;
  for (const raw of lexiconIterable) {
    const surface = String(raw);
    const c = scienceStem(surface);
    if (seenStem.has(c)) continue;
    seenStem.add(c);
    if (c.length < (minCandLen || minLen)) continue;
    const d = typoMatchScore(q, c);
    if (d == null) continue;
    if (d < bestD) {
      bestD = d;
      best = c;
      tie = false;
    } else if (d === bestD && c !== best) {
      tie = true;
    }
  }
  if (best == null || (bestD > 0 && tie)) return null;
  return best;
}

/** Normalize every token: repair typos in ask/stop words (any position in the sentence). */
function normalizeQuestionTokens(tokens) {
  if (!tokens || !tokens.length) return tokens || [];
  const fn = scienceFunctionLexicon();
  return tokens.map(w => {
    if (!/^[a-z]+$/i.test(w)) return w;
    const lower = w.toLowerCase();
    if (fn.has(lower)) return lower;
    const fixed = fuzzyBestInLexicon(lower, fn, 2);
    if (fixed && fn.has(fixed) && levenshtein(lower, fixed) <= 1) return fixed;
    return lower;
  });
}

function scienceTokensForMatch(text) {
  return normalizeQuestionTokens(scienceTokens(text));
}

function scienceTokens(text) {
  const s = String(text || "").toLowerCase().replace(/(\d),(?=\d)/g, "$1");
  return s.match(/\d+(?:\.\d+)?%?|[a-z]+/g) || [];
}

function scienceStem(word) {
  let w = word;
  if (w.length > 5 && /(?:s|ch|sh|x|z)es$/.test(w)) w = w.slice(0, -2);
  else if (w.length > 4 && w.endsWith("s") && !w.endsWith("ss")) w = w.slice(0, -1);
  if (w.length > 5 && w.endsWith("ing")) w = w.slice(0, -3);
  else if (w.length > 4 && w.endsWith("ied")) w = w.slice(0, -3) + "y";
  else if (w.length > 4 && w.endsWith("ed")) w = w.slice(0, -2);
  if (w.length > 3 && /(.)\1$/.test(w) && !/[aeiou]/.test(w[w.length - 1])) w = w.slice(0, -1);
  if (w.length > 4 && w.endsWith("e") && !w.endsWith("ee")) w = w.slice(0, -1);
  return w;
}

function levenshtein(a, b) {
  if (a === b) return 0;
  let la = a.length;
  let lb = b.length;
  if (!la) return lb;
  if (!lb) return la;
  if (la > lb) {
    const t = a;
    a = b;
    b = t;
    la = a.length;
    lb = b.length;
  }
  let prev = new Array(lb + 1);
  let curr = new Array(lb + 1);
  for (let j = 0; j <= lb; j++) prev[j] = j;
  for (let i = 1; i <= la; i++) {
    curr[0] = i;
    for (let j = 1; j <= lb; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      curr[j] = Math.min(prev[j] + 1, curr[j - 1] + 1, prev[j - 1] + cost);
    }
    const swap = prev;
    prev = curr;
    curr = swap;
  }
  return prev[lb];
}

function lessonVocabMatchFuzzy(q, set) {
  if (scienceStem(q).length < 3) return null;
  return fuzzyBestInLexicon(q, set, 3);
}

/**
 * Match a question topic stem to vocabulary in a lesson word set (exact, then fuzzy).
 * Returns the matched vocab stem, or null if none or ambiguous.
 */
function lessonVocabMatch(query, set) {
  const d = lessonVocabMatchDetailed(query, set);
  return d ? d.match : null;
}

/** @returns {{ match: string, fuzzy: boolean } | null} */
function lessonVocabMatchDetailed(query, set) {
  const q = scienceStem(query);
  if (set.has(query)) return { match: query, fuzzy: false };
  if (set.has(q)) return { match: q, fuzzy: false };
  const fuzzy = lessonVocabMatchFuzzy(q, set);
  if (fuzzy) return { match: fuzzy, fuzzy: true };
  return null;
}

function vocabDisplayFromFact(vocabStem, fact) {
  const texts = [fact && fact.text, fact && fact.question].filter(Boolean);
  let best = "";
  for (let t = 0; t < texts.length; t++) {
    const text = String(texts[t]);
    const re = /\d+(?:\.\d+)?%?|[a-z]+/gi;
    let m;
    while ((m = re.exec(text)) !== null) {
      const w = m[0];
      const lower = w.toLowerCase();
      if (SCIENCE_STOP.has(lower)) continue;
      if (queryStemMatchesVocab(vocabStem, scienceStem(lower))) {
        if (w.length > best.length) best = w;
      }
    }
  }
  return best || vocabStem;
}

function stemMatchedInHit(stem, hitSet) {
  if (!hitSet || !hitSet.size) return null;
  if (hitSet.has(stem)) return stem;
  for (const h of hitSet) {
    if (queryStemMatchesVocab(stem, h)) return h;
  }
  return null;
}

function normalizeTypoSuggestQuestion(text) {
  let s = String(text || "").trim().replace(/\?+$/, "").trim();
  if (!s) return "";
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/**
 * Build a clean question: fix typo tokens, drop words that did not match the lesson, one "?".
 * @param {{ hit?: string[], questionWords?: string[] } | null} matchMeta from rankLessons hit
 */
function buildTypoSuggestQuestion(prompt, typoFixes, fact, matchMeta) {
  if (!fact) return "";
  const hitList = (matchMeta && matchMeta.hit) || [];
  const hitSet = new Set(hitList);
  const hasHitFilter = hitSet.size > 0;
  const fixStemToMatch = new Map();
  for (const f of typoFixes || []) fixStemToMatch.set(scienceStem(f.asked), f.matched);

  const storedQ = String(fact.question || "").trim();
  if (
    storedQ &&
    hitSet.size &&
    questionContent(storedQ).length &&
    questionContent(storedQ).every(w => stemMatchedInHit(w, hitSet))
  ) {
    const canonical = normalizeTypoSuggestQuestion(storedQ);
    const raw = String(prompt || "").trim().replace(/\?+$/, "").trim().toLowerCase();
    if (canonical && canonical.toLowerCase() !== raw) return canonical + "?";
  }

  const parts = [];
  for (const w of scienceTokensForMatch(prompt)) {
    if (SCIENCE_STOP.has(w)) {
      parts.push(w);
      continue;
    }
    const stem = scienceStem(w);
    let vocabStem = stemMatchedInHit(stem, hitSet);
    if (!vocabStem && fixStemToMatch.has(stem)) vocabStem = fixStemToMatch.get(stem);
    if (!vocabStem && hasHitFilter) continue;
    if (!vocabStem) vocabStem = stem;
    parts.push(vocabDisplayFromFact(vocabStem, fact));
  }
  if (!parts.length) return "";
  let out = normalizeTypoSuggestQuestion(parts.join(" "));
  const raw = String(prompt || "").trim().replace(/\?+$/, "").trim();
  if (!out || out.toLowerCase() === raw.toLowerCase()) return "";
  return out + "?";
}

/** Show “Did you mean …?” when typos helped but the question was not a full word match. */
function shouldSuggestTypo(hit) {
  if (!hit || !hit.typoFixes || !hit.typoFixes.length) return false;
  if (hit.coverage < 0.72) return true;
  if (hit.misses > 0) return true;
  return false;
}

function tryPartialTypoPick(ranked) {
  if (!ranked.length) return null;
  const h = ranked[0];
  if (!h.typoFixes || !h.typoFixes.length) return null;
  if (h.coverage >= 0.72) return null;
  if (h.coverage < 0.35) return null;
  const words = h.questionWords;
  if (!words || !words.length) return null;
  const wordCov = h.hit.length / words.length;
  if (wordCov <= 0.5) return null;
  if (h.rare > 2) return null;
  return h;
}

function setHasLessonWord(set, word) {
  return lessonVocabMatch(word, set) != null;
}

function queryStemMatchesVocab(queryStem, vocabStem) {
  if (queryStem === vocabStem) return true;
  return lessonVocabMatch(queryStem, new Set([vocabStem])) === vocabStem;
}

function askShape(prompt) {
  const tokens = scienceTokensForMatch(prompt);
  return SCIENCE_ASK.find(k => tokens.includes(k)) || "";
}

function lessonWords(text) {
  const set = new Set();
  for (const w of scienceTokens(text)) {
    if (SCIENCE_STOP.has(w)) continue;
    set.add(w);
    set.add(scienceStem(w));
  }
  return set;
}

function topicWordSet(text) {
  const s = String(text || "").toLowerCase().replace(/(\d),(?=\d)/g, "$1");
  const tokens = s.match(/\d+(?:\.\d+)?%?|[a-z]+/g) || [];
  const set = new Set();
  for (let i = 0; i < tokens.length; i++) {
    if (i > 0 && tokens[i - 1] === "than") continue;
    const w = tokens[i];
    if (SCIENCE_STOP.has(w)) continue;
    set.add(w);
    set.add(scienceStem(w));
  }
  return set;
}

function questionContent(prompt) {
  const qc = [];
  const seen = new Set();
  for (const w of scienceTokensForMatch(prompt)) {
    if (SCIENCE_STOP.has(w)) continue;
    const s = scienceStem(w);
    if (seen.has(s)) continue;
    seen.add(s);
    qc.push(s);
  }
  return qc;
}

function rankLessons(prompt, lessons) {
  if (!lessons || !lessons.length) return [];
  const docs = lessons.map(f => {
    const topic = topicWordSet(f.text);
    for (const w of lessonWords(f.question || "")) topic.add(w);
    return topic;
  });
  const df = new Map();
  for (const set of docs) for (const w of set) df.set(w, (df.get(w) || 0) + 1);
  const N = docs.length;
  const weight = w => {
    const d = df.get(w) || 0;
    return d ? Math.log((N + 1) / d) : 2.6;
  };
  const qc = questionContent(prompt);
  if (!qc.length) return [];
  const shape = new Set(["many", "much"]);
  const scored = qc.filter(w => !shape.has(w));
  const words = scored.length ? scored : qc;
  const total = words.reduce((sum, w) => sum + weight(w), 0);
  const hits = [];
  const askedShape = askShape(prompt);
  docs.forEach((set, i) => {
    const hit = [];
    const typoFixes = [];
    for (const w of words) {
      const d = lessonVocabMatchDetailed(w, set);
      if (d) {
        hit.push(d.match);
        if (d.fuzzy) typoFixes.push({ asked: w, matched: d.match });
      }
    }
    const misses = words.length - hit.length;
    if (!hit.length || hit.length * 2 <= words.length) return;
    const sc = hit.reduce((sum, w) => sum + (df.has(w) ? weight(w) : 0), 0);
    let cov = sc / total;
    const rare = Math.min(...hit.map(w => df.get(w) || 99));
    const first = scienceTokens(lessons[i].text).find(w => !SCIENCE_STOP.has(w));
    const aboutThatWord = qc.length === 1 && first && scienceStem(first) === qc[0];
    const askedThis = questionContent(lessons[i].question || "").join(" ") === qc.join(" ");
    const wordCov = hit.length / words.length;
    const qWords = new Set(questionContent(lessons[i].question || ""));
    const qOverlap = hit.filter(w => {
      for (const qw of qWords) {
        if (queryStemMatchesVocab(qw, w)) return true;
      }
      return false;
    }).length;
    const lessonShape = askShape(lessons[i].question || "");
    const looseWhen = misses === 1 && hit.length >= 2 && qOverlap >= 2 && askedShape === "when" && lessonShape === "when" && statesTime(lessons[i].text);
    if (looseWhen && cov < 0.72) cov = 0.72;
    const strong = cov >= 0.72 && wordCov > 0.5 && (!(hit.length === 1 && rare > 2) || aboutThatWord || askedThis);
    const partial = cov >= 0.35 && rare <= 2;
    if (!strong && !partial) return;
    hits.push({
      coverage: cov,
      rare,
      hit,
      fact: lessons[i],
      misses,
      shape: lessonShape && lessonShape === askedShape ? 1 : 0,
      qOverlap,
      typoFixes,
      questionWords: words
    });
  });
  hits.sort((a, b) => {
    if (b.coverage !== a.coverage) return b.coverage - a.coverage;
    if (b.shape !== a.shape) return b.shape - a.shape;
    if (a.misses || b.misses) {
      if (b.qOverlap !== a.qOverlap) return b.qOverlap - a.qOverlap;
    }
    return 0;
  });
  return hits;
}

function lessonAnchorsPrompt(prompt, fact) {
  if (!fact) return false;
  if (questionMatches(prompt, fact)) return true;
  if (questionPromptOverlap(prompt, fact)) return true;
  if (asksDefinition(prompt)) {
    const subject = questionContent(prompt)[0];
    if (subject && definesSubject(fact.text, subject)) return true;
  }
  return false;
}

/** Two ranked hits but neither stored question (nor definition subject) fits the prompt. */
function isUnanchoredDualPick(picked, prompt) {
  if (!picked || picked.length !== 2 || !prompt) return false;
  return picked.every(h => !lessonAnchorsPrompt(prompt, h.fact));
}

function trimSplitWordLessonPick(chosen, prompt) {
  if (!chosen || chosen.length !== 2) return chosen || [];
  if (isSplitWordLessonPair(chosen) || isUnanchoredDualPick(chosen, prompt)) return [chosen[0]];
  return chosen;
}

function selectLessons(hits, prompt) {
  if (!hits.length) return [];
  const rest = hits.slice(1).find(h => h.hit.some(w => !hits[0].hit.includes(w)));
  if (hits[0].coverage < 0.72) {
    return trimSplitWordLessonPick(rest ? [hits[0], rest] : [], prompt);
  }
  const chosen = [hits[0]];
  const restIsAnotherQuestion = hits[0].shape && rest && !rest.shape;
  if (rest && !restIsAnotherQuestion && (hits[0].coverage - rest.coverage < 0.08 || rest.hit.some(w => !hits[0].hit.includes(w)))) {
    chosen.push(rest);
  } else if (!restIsAnotherQuestion) {
    const tied = hits.slice(1).find(h =>
      hits[0].coverage - h.coverage < 0.08 &&
      h.fact.text !== hits[0].fact.text &&
      !(hits[0].shape && !h.shape)
    );
    if (tied) chosen.push(tied);
  }
  return trimSplitWordLessonPick(chosen, prompt);
}

/**
 * Two ranked hits each matched different query words (e.g. “american” + “nation” → two unrelated lessons).
 * Applies to every pack in SCIENCE_LIBRARY and to taught rows — not science-only.
 */
function isSplitWordLessonPair(picked) {
  if (!picked || picked.length !== 2) return false;
  const words = picked[0].questionWords || picked[1].questionWords;
  if (!words || words.length < 2) return false;
  const a = picked[0];
  const b = picked[1];
  if (!a.hit || !a.hit.length || !b.hit || !b.hit.length) return false;
  if (a.misses === 0 || b.misses === 0) return false;
  const setA = new Set(a.hit);
  for (const w of b.hit) if (setA.has(w)) return false;
  return a.hit.length + b.hit.length >= words.length;
}

function mapUserLessons(userLessons) {
  return (userLessons || []).map((item, i) => {
    if (item && typeof item === "object") {
      return {
        id: item.id || ("learned-" + (i + 1)),
        category: item.category || "Learned",
        text: item.text || "",
        question: item.question || ""
      };
    }
    return { id: "learned-" + (i + 1), category: "Learned", text: String(item || ""), question: "" };
  }).filter(f => f.text);
}

function rankAllLessons(prompt, userLessons) {
  return rankLessons(prompt, mapUserLessons(userLessons).concat(SCIENCE_LIBRARY));
}

function polarAnswer(prompt, factText) {
  const tokens = scienceTokens(prompt);
  const polar = new Set(["is", "are", "do", "does", "did", "can", "could", "has", "have"]);
  if (!tokens.length || !polar.has(tokens[0])) return null;
  const qc = questionContent(prompt);
  if (!qc.length) return null;
  const subject = qc[0];
  const claim = qc.slice(1);
  const clauses = factText.split(/\b(?:but|though|although|while|whereas)\b|;/i);
  const aboutSubject = clauses.map(lessonWords).find(set => setHasLessonWord(set, subject));
  const clause = aboutSubject || lessonWords(factText);
  if (!setHasLessonWord(clause, subject)) return "no";
  if (!claim.length) return "yes";
  return claim.every(w => setHasLessonWord(clause, w)) ? "yes" : "no";
}

function parseKnowledgeLine(text) {
  const raw = String(text || "").trim();
  if (!raw) return null;
  const q = raw.indexOf("?");
  if (q === -1) {
    if (/^(what|why|how|is|are|do|does|did|where|who|when|can|has|have)\b/i.test(raw)) return null;
    if (scienceTokens(raw).length < 4) return null;
    return { text: raw, question: "" };
  }
  const question = raw.slice(0, q + 1).trim();
  const answer = raw.slice(q + 1).trim();
  if (scienceTokens(answer).length < 4) return null;
  return { question, text: answer };
}

function looksLikeLesson(text) {
  const lesson = parseKnowledgeLine(text);
  if (!lesson || /[?]/.test(text)) return false;
  if (/^(tell|show|explain|describe|give|write|list|please|make|draw)\b/i.test(String(text).trim())) return false;
  return scienceTokens(text).length >= 6;
}

function asksQuantity(prompt) {
  const tokens = scienceTokens(prompt);
  const how = tokens.indexOf("how");
  return how !== -1 && (tokens[how + 1] === "many" || tokens[how + 1] === "much");
}

function statesCount(text) {
  if (/\d/.test(String(text || ""))) return true;
  const counts = new Set("one two three four five six seven eight nine ten eleven twelve".split(" "));
  return scienceTokens(text).some(w => counts.has(w));
}

function normalizeLessonQuestion(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/\?+$/, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** Optional equivalent stored questions (same lesson). Midel identity uses separate rows per ask. */
const LESSON_QUESTION_ALIASES = [];

function lessonQuestionsEquivalent(want, stored) {
  if (want === stored) return true;
  for (const group of LESSON_QUESTION_ALIASES) {
    if (group.includes(want) && group.includes(stored)) return true;
  }
  return false;
}

function exactQuestionMatch(prompt, fact) {
  const want = normalizeLessonQuestion(prompt);
  const stored = normalizeLessonQuestion(fact && fact.question);
  return !!(want && stored && lessonQuestionsEquivalent(want, stored));
}

function questionMatches(prompt, fact) {
  if (exactQuestionMatch(prompt, fact)) return true;
  const asked = questionContent(fact && fact.question);
  const qc = questionContent(prompt);
  return qc.length >= 1 && asked.length === qc.length && asked.join(" ") === qc.join(" ");
}

/** Rank-shaped hit when the user prompt equals a stored lesson question (incl. all-stop-word asks). */
function exactQuestionHitForPrompt(prompt, userLessons) {
  const lessons = mapUserLessons(userLessons).concat(SCIENCE_LIBRARY);
  const matches = lessons.filter(f => f && f.text && f.question && exactQuestionMatch(prompt, f));
  if (!matches.length) return null;
  matches.sort((a, b) => {
    const pri = f => (f.category === "Learned" || f.category === "Yours" ? 1 : 0);
    return pri(b) - pri(a);
  });
  const fact = matches[0];
  const norm = t => String(t || "").trim().toLowerCase().replace(/\s+/g, " ");
  const seen = new Set([norm(fact.text)]);
  const sameQuestion = [];
  matches.slice(1).forEach(f => {
    const k = norm(f.text);
    if (seen.has(k) || sameQuestion.length >= 2) return;
    seen.add(k);
    sameQuestion.push(f);
  });
  return {
    sameQuestion,
    coverage: 1,
    rare: 0,
    hit: ["exact"],
    fact,
    misses: 0,
    shape: 1,
    qOverlap: 99,
    typoFixes: [],
    questionWords: scienceTokensForMatch(prompt)
  };
}

/** Stored lesson question extends the user's (unfinished) question with the same ask-word and topic order. */
function questionPromptOverlap(prompt, fact) {
  const qc = questionContent(prompt);
  const stored = questionContent(fact && fact.question);
  if (!qc.length || !stored.length || stored.length < qc.length) return false;
  const shape = askShape(prompt);
  const lessonShape = askShape(fact && fact.question);
  if (shape && lessonShape && shape !== lessonShape) return false;
  for (let i = 0; i < qc.length; i++) {
    if (stored[i] !== qc[i]) return false;
  }
  return true;
}

function pickUnfinishedQuestionHit(prompt, ranked) {
  const hits = ranked.filter(h => questionPromptOverlap(prompt, h.fact) && h.coverage >= 0.72);
  if (!hits.length) return null;
  const qlen = questionContent(prompt).length;
  hits.sort((a, b) => {
    const extraA = questionContent(a.fact.question).length - qlen;
    const extraB = questionContent(b.fact.question).length - qlen;
    if (extraA !== extraB) return extraA - extraB;
    if (b.coverage !== a.coverage) return b.coverage - a.coverage;
    return (b.fact.category === "Learned") - (a.fact.category === "Learned");
  });
  return hits[0];
}

function asksDefinition(prompt) {
  const qc = questionContent(prompt);
  if (qc.length !== 1) return false;
  const tokens = scienceTokens(prompt);
  return !tokens.some(w => w === "when" || w === "where" || w === "who" || w === "why" || w === "how");
}

function definesSubject(text, subject) {
  const tokens = scienceTokens(text);
  const i = tokens.findIndex(w => queryStemMatchesVocab(subject, scienceStem(w)));
  if (i < 0) return false;
  for (let k = i + 1; k < tokens.length && k < i + 5; k++) {
    const w = tokens[k];
    if (w === "is" || w === "are") return true;
    if (!SCIENCE_STOP.has(w)) return false;
  }
  return false;
}

function asksWhen(prompt) {
  return scienceTokens(prompt).includes("when");
}

function statesTime(text) {
  return /\b\d{3,}|bce|bc\b|ago\b|century/i.test(String(text || ""));
}

function nearTop(hits) {
  if (!hits.length) return [];
  const top = hits[0].coverage;
  return hits.filter(h => top - h.coverage < 0.08);
}

function syntheticLessonHit(fact, prompt) {
  return {
    coverage: 1,
    rare: 0,
    hit: ["exact"],
    fact,
    misses: 0,
    shape: 1,
    qOverlap: 99,
    typoFixes: [],
    questionWords: scienceTokensForMatch(prompt)
  };
}

/** Same ask-subject as "what is benzodiazepine?" even if wording differs slightly from stored question. */
function definitionSubjectQuestionHit(prompt, userLessons) {
  const qc = questionContent(prompt);
  if (qc.length !== 1) return null;
  const wantStem = scienceStem(qc[0]);
  const lessons = mapUserLessons(userLessons).concat(SCIENCE_LIBRARY);
  const matches = lessons.filter(function (f) {
    if (!f || !f.text || !f.question) return false;
    const sq = questionContent(f.question);
    return sq.length === 1 && scienceStem(sq[0]) === wantStem;
  });
  if (!matches.length) return null;
  matches.sort(function (a, b) {
    if (a.category === "Wikipedia" && b.category !== "Wikipedia") return -1;
    if (b.category === "Wikipedia" && a.category !== "Wikipedia") return 1;
    return (Number(a.id) || 0) - (Number(b.id) || 0);
  });
  return syntheticLessonHit(matches[0], prompt);
}

/** Library answer for any prompt — all fact packs + optional taught rows. */
function answerFromLessons(prompt, userLessons) {
  let picked = null;
  const exactHit = exactQuestionHitForPrompt(prompt, userLessons);
  if (exactHit) picked = [exactHit];
  if (!picked) {
    const subjectHit = definitionSubjectQuestionHit(prompt, userLessons);
    if (subjectHit) picked = [subjectHit];
  }
  const ranked = rankAllLessons(prompt, userLessons);
  const learnedHit = ranked.find(h => h.fact.category === "Learned");
  const best = ranked[0];
  if (!picked) {
    const asked = ranked.filter(h => questionMatches(prompt, h.fact));
    asked.sort((a, b) => (b.fact.category === "Learned") - (a.fact.category === "Learned"));
    if (asked.length) picked = [asked[0]];
  }
  if (!picked) {
    const unfinished = pickUnfinishedQuestionHit(prompt, ranked);
    if (unfinished) picked = [unfinished];
  }
  if (!picked && asksDefinition(prompt)) {
    const subject = questionContent(prompt)[0];
    const defs = nearTop(ranked).filter(h => definesSubject(h.fact.text, subject));
    if (defs.length) picked = [defs[0]];
  }
  if (!picked && asksWhen(prompt)) {
    const dated = nearTop(ranked).filter(h => statesTime(h.fact.text));
    if (dated.length) picked = [dated[0]];
  }
  if (!picked && asksQuantity(prompt)) {
    const numbered = ranked.filter(h => statesCount(h.fact.text));
    numbered.sort((a, b) => {
      if (b.hit.length !== a.hit.length) return b.hit.length - a.hit.length;
      const learned = (b.fact.category === "Learned") - (a.fact.category === "Learned");
      if (learned) return learned;
      return b.coverage - a.coverage;
    });
    picked = numbered.length ? [numbered[0]] : [];
  }
  if (!picked || !picked.length) {
    const yoursAnswers = learnedHit && best && learnedHit.hit.length >= best.hit.length;
    if (asksDefinition(prompt)) {
      const qc = questionContent(prompt);
      if (qc.length === 1) {
        const subject = qc[0];
        const defs = ranked.filter(function (h) {
          return definesSubject(h.fact.text, subject);
        });
        if (defs.length) picked = [defs[0]];
        else picked = [];
      } else {
        picked = yoursAnswers ? [learnedHit] : selectLessons(ranked, prompt);
      }
    } else {
      picked = yoursAnswers ? [learnedHit] : selectLessons(ranked, prompt);
    }
  }
  if (!picked.length) {
    const partialTypo = tryPartialTypoPick(ranked);
    if (partialTypo) picked = [partialTypo];
  }
  if (!picked.length) return null;
  picked = trimSplitWordLessonPick(picked, prompt);
  const conflict = picked.length === 2 && (
    picked[0].fact.category !== picked[1].fact.category ||
    Math.abs(picked[0].coverage - picked[1].coverage) < 0.08
  );
  const sentences = picked.map(h => h.fact.text);
  const source = lessonReasonSource(picked, conflict);
  const yn = !conflict && picked.length === 1 ? polarAnswer(prompt, picked[0].fact.text) : null;
  const text = yn || ((conflict ? "The library says both: " : "") + sentences.join(" "));
  const primary = picked[0];
  const suggestQuestion = shouldSuggestTypo(primary)
    ? buildTypoSuggestQuestion(prompt, primary.typoFixes, primary.fact, {
        hit: primary.hit,
        questionWords: primary.questionWords
      })
    : "";
  const typoPartial = primary.coverage < 0.72 && primary.typoFixes && primary.typoFixes.length > 0;
  return {
    text,
    word: text,
    coverage: primary.coverage,
    facts: picked.map(h => h.fact),
    sameQuestion: exactHit && picked[0] === exactHit ? exactHit.sameQuestion : [],
    reason: yn ? source + " — " + sentences[0] : source,
    suggestQuestion,
    typoPartial
  };
}

function lessonDisplaySource(fact) {
  if (!fact || fact.id == null) return "from Lesson";
  if (fact.category === "Wikipedia") return "Deep network learned #" + fact.id;
  return "from " + (fact.category || "Lesson") + " #" + fact.id;
}

function lessonReasonSource(picked, conflict) {
  if (!picked || !picked.length) return "";
  if (picked.length === 1 && picked[0].fact && picked[0].fact.category === "Wikipedia") {
    return lessonDisplaySource(picked[0].fact);
  }
  const ids = picked.map(h => {
    const f = h.fact;
    if (f && f.category === "Wikipedia") return "Deep network learned #" + f.id;
    return (f.category || "Lesson") + " #" + f.id;
  }).join(" and ");
  return (conflict ? "two lessons, " : "from ") + ids;
}

function searchScienceLibrary(prompt) {
  return answerFromLessons(prompt, []);
}

/** Stored lesson question for a deep pass when the user prompt is loose (e.g. titanium?). */
function lessonDeepQuestion(facts, prompt) {
  if (!facts || !facts.length) return prompt;
  const fact = facts[0];
  const stored = String(fact.question || "")
    .trim()
    .replace(/\?+$/, "");
  if (!stored) return prompt;
  if (questionMatches(prompt, fact)) return stored + " ?";
  if (questionPromptOverlap(prompt, fact)) return stored + " ?";
  if (asksDefinition(prompt)) {
    const subject = questionContent(prompt)[0];
    if (subject && definesSubject(fact.text, subject)) return stored + " ?";
  }
  const asked = scienceTokens(prompt);
  if (asked.length === 1 && scienceStem(asked[0])) {
    const stem = scienceStem(asked[0]);
    if (scienceTokens(fact.text).some(w => queryStemMatchesVocab(stem, scienceStem(w)))) return stored + " ?";
  }
  return prompt;
}
